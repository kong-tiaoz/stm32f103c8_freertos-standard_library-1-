#include "bsp_usart.h"
#include <stdarg.h>

bool g_log_output_enabled = true; // 新增全局控制变量

static QueueHandle_t xLogQueue = NULL;
static TaskHandle_t xLogTaskHandle = NULL;

static void Log_Task(void *pvParameters)
{
    char msg[LOG_MSG_MAX_LEN];
    while (1) {
        if (xQueueReceive(xLogQueue, msg, portMAX_DELAY) == pdTRUE) {
            Usart_SendString(DEBUG_USARTx, msg);
        }
    }
}

void Log_Init(void)
{
    xLogQueue = xQueueCreate(LOG_QUEUE_LENGTH, LOG_MSG_MAX_LEN);
    if (xLogQueue != NULL) {
        xTaskCreate(Log_Task, "Log_Task", 128, NULL, 1, &xLogTaskHandle);
    }
}

void Log_Printf(const char *format, ...)
{
    if (!g_log_output_enabled) {
        return; // 根据全局开关动态禁用输出
    }
    
    if (xLogQueue == NULL) {
        return; // 日志系统尚未初始化
    }

    char buffer[LOG_MSG_MAX_LEN];

    // 格式化变参字符串 (移除时间戳)
    va_list args;
    va_start(args, format);
    vsnprintf(buffer, LOG_MSG_MAX_LEN, format, args);
    va_end(args);

    // 将格式化后的字符串发送到队列
    // 采用超时0，如果在ISR中调用，需要特殊处理，但这里假设仅在任务中调用
    if (xTaskGetSchedulerState() != taskSCHEDULER_NOT_STARTED) {
        xQueueSendToBack(xLogQueue, buffer, 0);
    } else {
        // 如果调度器尚未启动，则直接阻塞发送，以防丢失初始化信息
        Usart_SendString(DEBUG_USARTx, buffer);
    }
}


